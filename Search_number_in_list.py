'''
Exercițiul 4: Căutarea unui element**
Cerinta: Caută un număr dat într-o listă și afișează dacă a fost găsit sau nu.
Input: `numbers = [5, 10, 15, 20, 25]`, `search_number = 15`
Output:
```
Numărul 15 a fost găsit în listă.
```
'''

numbers = [5, 10, 15, 20, 25]
search_number = 15

if search_number in numbers:
    print("Numărul 15 a fost găsit în listă.")
